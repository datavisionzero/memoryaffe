// Reproducible schema-oriented generator, version 1. No network/dependencies.
// Run: node generate.mjs [--check] from src/cli or the repository root.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const source = await readFile(new URL('../../docs/contracts/agent.openapi.json', import.meta.url), 'utf8');
const api = JSON.parse(source), schemas = api.components.schemas;
const name = k => k.replace(/^./, c => c.toUpperCase()).replace(/Id(s?)$/g, (_, s) => 'ID' + s);
function goType(s, indent = '') {
  if (s.$ref) return 'API' + s.$ref.split('/').at(-1);
  if (Array.isArray(s.type)) { const rest = s.type.filter(x => x !== 'null'); return rest.length === 1 ? '*' + goType({ ...s, type: rest[0] }, indent) : 'json.RawMessage'; }
  switch (s.type ?? typeof s.const) {
    case 'object': {
      const required = new Set(s.required ?? []);
      return 'struct {\n' + Object.entries(s.properties ?? {}).map(([key, value]) => { const optional = !required.has(key); const type = optional && Array.isArray(value.type) && value.type.includes('null') ? 'json.RawMessage' : goType(value, indent + '\t'); return indent + '\t' + name(key) + ' ' + (optional && !type.startsWith('*') && type !== 'json.RawMessage' ? '*' : '') + type + ' `json:"' + key + (optional ? ',omitempty' : '') + '"`'; }).join('\n') + '\n' + indent + '}';
    }
    case 'array': return '[]' + goType(s.items, indent);
    case 'string': return 'string';
    case 'integer': return 'int';
    case 'number': return 'float64';
    case 'boolean': return 'bool';
    default: return 'json.RawMessage';
  }
}
let generated = '// Code generated by generate.mjs v1 from agent.openapi.json; DO NOT EDIT.\npackage main\n\n';
let body = '';
for (const [key, value] of Object.entries(schemas)) body += 'type API' + key + ' ' + goType(value) + '\n\n';
if (body.includes('json.RawMessage')) generated += 'import "encoding/json"\n\n';
generated += 'const agentContractSHA256 = "' + createHash('sha256').update(source).digest('hex') + '"\n\n' + body;
generated += 'type agentOperationSpec struct {\nMethod string\nPath string\n}\nvar agentOperations = map[string]agentOperationSpec{\n';
for (const [path, verbs] of Object.entries(api.paths)) for (const [method, operation] of Object.entries(verbs)) generated += '\t' + JSON.stringify(operation.operationId) + ': {Method: ' + JSON.stringify(method.toUpperCase()) + ', Path: ' + JSON.stringify(path) + '},\n';
generated += '}\n';
// gofmt is deliberately a separate declared toolchain step; generated content
// is already valid Go. Drift compares semantic source independent of gofmt.
const target = new URL('./contract_generated.go', import.meta.url);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8');
  const normalize = s => s.replace(/\s+/g, '').replaceAll(',}', '}');
  if (normalize(current) !== normalize(generated)) { console.error('Go contract drift: run node src/cli/generate.mjs and gofmt'); process.exitCode = 1; }
  else console.log('Go contract generation matches agent.openapi.json');
} else { await writeFile(target, generated); console.log('Generated ' + fileURLToPath(target)); }
